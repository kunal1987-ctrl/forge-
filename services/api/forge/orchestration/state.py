"""Agent State definition for the FORGE LangGraph orchestration engine.

This module defines the central AgentState TypedDict tracking the lifecycle of an
autonomous code repair/task execution run across planning, retrieval, implementation,
sandboxed testing, and review.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, TypedDict


class TestResults(TypedDict, total=False):
    """Execution output from the Docker verification sandbox."""

    exit_code: int
    stdout: str
    stderr: str


class AgentState(TypedDict, total=False):
    """Central state representation flowing through the FORGE orchestration graph.

    Attributes:
        task_id: Unique task identifier string.
        repo_id: UUID string of the repository being modified.
        commit_sha: Base commit SHA string for the target repository revision.
        prompt: User task description and requirements.
        worktree_path: Ephemeral Git worktree directory on the host filesystem.
        plan: Structured breakdown of the task generated by the planner LLM.
        context_retrieved: Formatted code chunks and module context retrieved via hybrid RAG.
        generated_diff: Unified git diff generated by the implementer LLM.
        test_results: Sandboxed verification output with exit_code, stdout, and stderr.
        retry_count: Number of failed repair attempts executed so far.
        status: Current lifecycle state (e.g., 'planning', 'investigating',
            'implementing', 'verifying', 'awaiting_approval', 'failed').
    """

    task_id: str
    repo_id: str
    commit_sha: str
    prompt: str
    worktree_path: str
    plan: Dict[str, Any]
    context_retrieved: List[str]
    generated_diff: str
    test_results: Dict[str, Any]
    retry_count: int
    status: str
